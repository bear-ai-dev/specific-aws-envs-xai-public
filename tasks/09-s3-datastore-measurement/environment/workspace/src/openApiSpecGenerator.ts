import { SwaggerModule, DocumentBuilder } from '@nestjs/swagger';
import { writeFileSync } from 'fs';
import { NestFactory } from '@nestjs/core';
import { ValidationPipe } from '@nestjs/common';
import { AppModule } from './app.module';
import { TimingInterceptor } from './interceptors/timing.interceptor';
import { MeasurementModule } from './measurement/measurement.module';
import { PrivateAPIInvoicesModule } from './invoice/invoices.module';
import { PrivateAPIOfferingModule, PublicAPIOfferingModule } from './offering/offering.module';
import { PrivateAPIServicesModule, PublicAPIServicesModule } from './services/services.module';
import { BillingModule } from './billing/billing.module';
import { MargincalcModule } from './margincalc/margincalc.module';
import { FeatureRequestModule } from './featureRequest/featureRequest.module';
import { UsersModule } from './users/users.module';
import { OnboardingModule } from './onboarding/onboarding.module';
import { PrivateAPICustomerModule, PublicAPICustomerModule } from './customer/customer.module';
import { ScheduleModule } from '@nestjs/schedule';
import { PrivateAPIDimensionsModule, PublicAPIDimensionsModule } from './dimensions/dimensions.module';
import { CostModule } from './cost/cost.module';
import { MeasurementConfigModule } from './measurement-config/measurement-config.module';
import { PrivateAPISettingsModule } from './setting/settings.module';
import { PrivateAPIAnalyticsModule } from './analytics/analytics.module';
import { PrivateInboxModule } from './inbox/inbox.module';
import { UsageModule } from './usage/usage.module';

async function bootstrap() {
    const app = await NestFactory.create(AppModule);
    app.useGlobalInterceptors(new TimingInterceptor());
    app.useGlobalPipes(new ValidationPipe({ whitelist: true }));
    const config = new DocumentBuilder()
        .setTitle('MeteringCo API')
        .setDescription(
            'Welcome to the API! MeteringCo makes it easy to bill customers based on usage. We take care of the measurement of usage, creating offerings, processing payment and analyzing cost.'
        )
        .setVersion(`0.4-alpha`)
        .addTag(
            'Authentication',
            `MeteringCo API offers one form of authentication:
        <br/>
        <b>Bearer Authentication - Client Credentials</b>
        <br>
        <br>
        To access the API first get your client ClientID and Secret my emailing founders@meteringco.tech, after you have gotten your credentials, you must pass them into the Body of a POST request to the auth endpoint: https://example-tenant.us.auth0.com/oauth/token
        <br>
        <br>
        See the Node JS fetch example below for a complete request which can be made

        // This assumes you've set your AUTH0_CLIENT_ID and AUTH0_CLIENT_SECRET as process.env values
        const response = await fetch(
            'https://example-tenant.us.auth0.com/oauth/token',
            {
              method: 'POST',
              headers: { 'content-type': 'application/json' },
              body: JSON.stringify({
                client_id: process.env.AUTH0_CLIENT_ID,
                client_secret: process.env.AUTH0_CLIENT_SECRET,
                audience: 'https://example1234.execute-api.us-east-1.amazonaws.com',
                grant_type: 'client_credentials',
              }),
            },
          );


`
        )
        .addTag(
            'Offerings',
            'An offering represents, a SKU to your business. As an example a SaaS business may have a public offering where users pay per megabyte, and they could have a different offering with a big client where they pay per Gb'
        )
        .addTag(
            'Services',
            'A service is a specific implementation of a SaaS offering, for example you may have multiple services per customer, a dev service and a prod service would be two examples. Each service can have the same offering or different offerings.'
        )
        .addTag(
            'Customers',
            'Customers are the clients who are interacting with your SaaS. Importantly for MeteringCo we need to know your customers Identifier and the payment channel which to charge them through'
        )
        .addTag(
            'Dimensions',
            'Create and Manage Dimensions to be used with offerings, includes the aggregation information as well as units and dimension Price. For example if an offering has Uptime and Provisioned Capacity, there should one dimension for each'
        )
        .addTag(
            'Invoices',
            'Invoices are generated by MeteringCo and sent to your customers. You can also use the API to get a list of invoices for a customer, or a specific invoice'
        )
        .addTag(
            'Analytics',
            'MeteringCo provides a number of analytics endpoints to help you understand your business. These include: Cost, Usage, Revenue, Profit, and Margins'
        )
        .addTag('Settings', 'Manage MeteringCo platform settings')
        .addServer('http://localhost:3000/', 'local')
        .addServer('https://api.dev.meteringco.tech', 'dev')
        .addServer('https://api.qa.meteringco.tech', 'qa')
        .addServer('https://api.int.meteringco.tech', 'integration')
        .addServer('https://api.prod.meteringco.tech', 'prod')
        .addBearerAuth({ type: 'http', scheme: 'bearer', bearerFormat: 'JWT' }, 'bearer')
        .build();
    const document = SwaggerModule.createDocument(app, config, {
        include: [
            MeasurementModule,
            PrivateAPIInvoicesModule,
            PublicAPIOfferingModule,
            PrivateAPIOfferingModule,
            PublicAPIServicesModule,
            PrivateAPIServicesModule,
            BillingModule,
            AppModule,
            MargincalcModule,
            FeatureRequestModule,
            UsersModule,
            OnboardingModule,
            PublicAPICustomerModule,
            PrivateAPICustomerModule,
            ScheduleModule,
            PublicAPIDimensionsModule,
            PrivateAPIDimensionsModule,
            CostModule,
            MeasurementConfigModule,
            PrivateAPISettingsModule,
            PrivateAPIInvoicesModule,
            PrivateAPIAnalyticsModule,
            PrivateInboxModule,
            UsageModule,
        ],
    });
    writeFileSync('./docs/open-api-private-spec.json', JSON.stringify(document));
    // For some reason the app doesn't want to close so we need to manually call app.close, I believe there may be some service which cannot initalize underneath (likely redis and bullmq)
    await app.close();
    console.log('finished!');
}
bootstrap();
